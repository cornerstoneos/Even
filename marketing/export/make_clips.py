"""App-first step clips, 1080x1920, 30fps, silent. Built from fresh recordings of the LIVE app (even-os.com), one per language.

Each rundir comes from run2.mjs + build_rec.py: rec.mp4 (804x1748), events.json (hold windows + element rects in CSS px),
costsheet.pdf / proposal.pdf (generated by the app itself). Callouts are placed from the element rects measured during the
recording, so every box sits on the field it names."""
import sys, os, json, math, subprocess
import numpy as np
from PIL import Image, ImageDraw, ImageFont, ImageFilter
RUNS = {'en': sys.argv[1], 'es': sys.argv[2]}; OUT = sys.argv[3]; os.makedirs(OUT, exist_ok=True)
W, H = 1080, 1920; BG = (8, 8, 8); GOLD = (212, 175, 55); WHITE = (255, 255, 255)
F = lambda w, s: ImageFont.truetype('/usr/share/fonts/opentype/inter/Inter-%s.otf' % w, s)
PW, PH = 690, 1500; PX, PY = (W - PW) // 2, 300; SW, SH = 804, 1748; K = PW / SW
LOGO = '/home/user/Even/marketing/public/logo.png'
logo = Image.open(LOGO).convert('RGBA')

L = {
 'en': dict(scope='Type it, paste it, or upload plans', city='Pick your city', trade='Pick your trade', margins='Overhead, profit, risk: yours',
            labor='Your labor multiplier too', q0='Only the ones that change the price', q2='Tap an answer', price='Your bid', rng='With its range',
            final='You set the final price', grid='Two outputs, one tap each', cost='Cost sheet: only you see it', prop='Client proposal, clean price',
            steps=['Step 1', 'Step 2', 'Step 3', 'Step 4', 'Step 5'],
            titles=['Describe the job.', 'You set the margins.', 'Answer a few questions.', 'Get your bid.', 'Send the proposal.']),
 'es': dict(scope='Escríbelo, pégalo o sube planos', city='Elige tu ciudad', trade='Elige tu oficio', margins='Gastos, ganancia, riesgo: tuyos',
            labor='Tu multiplicador de mano de obra', q0='Solo las que cambian el precio', q2='Toca una respuesta', price='Tu oferta', rng='Con su rango',
            final='Tú pones el precio final', grid='Dos documentos, un toque', cost='Hoja de costos: solo tú', prop='Propuesta limpia para el cliente',
            steps=['Paso 1', 'Paso 2', 'Paso 3', 'Paso 4', 'Paso 5'],
            titles=['Describe el trabajo.', 'Tú pones los márgenes.', 'Responde unas preguntas.', 'Recibe tu oferta.', 'Envía la propuesta.']),
}
IDS = ['1-describe', '2-margins', '3-questions', '4-bid', '5-proposal']

def bg():
    img = Image.new('RGB', (W, H), BG); d = ImageDraw.Draw(img); t = math.tan(math.radians(60)); sp = 46
    for off in range(-int(H / t) - sp, W + sp, sp):
        d.line((off, 0, off + H / t, H), fill=(24, 20, 8), width=1); d.line((off + H / t, 0, off, H), fill=(24, 20, 8), width=1)
    vig = Image.new('L', (W, H), 0); ImageDraw.Draw(vig).ellipse((-250, -150, W + 250, H + 150), fill=255); vig = vig.filter(ImageFilter.GaussianBlur(260))
    a = np.asarray(img, dtype=np.float32) * (np.asarray(vig, dtype=np.float32)[..., None] / 255 * 0.85 + 0.15)
    return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8))
BG_IMG = bg()

def frame_png(step, title, path):
    img = BG_IMG.copy(); d = ImageDraw.Draw(img)
    lg = logo.resize((int(logo.width * 64 / logo.height), 64)); img.paste(lg, (60, 70), lg)
    d.text((60 + lg.width + 16, 76), 'even.', font=F('Bold', 52), fill=WHITE)
    s = step.upper(); f = F('SemiBold', 34); d.text((W - 60 - d.textlength(s, font=f), 92), s, font=f, fill=GOLD)
    d.text((60, 190), title, font=F('Bold', 64), fill=WHITE)
    d.rounded_rectangle((PX - 8, PY - 8, PX + PW + 8, PY + PH + 8), radius=44, outline=(70, 58, 20), width=4)
    cf = F('SemiBold', 34); t = 'even-os.com'; d.text(((W - d.textlength(t, font=cf)) / 2, 1838), t, font=cf, fill=GOLD)
    img.save(path)

def callout_png(box, label, path, below=False):
    """box = (x0,y0,x1,y1) in recording pixels (804x1748)."""
    x0, y0, x1, y1 = box; X0, Y0, X1, Y1 = PX + x0 * K, PY + y0 * K, PX + x1 * K, PY + y1 * K
    pad = 8; X0, Y0, X1, Y1 = X0 - pad, Y0 - pad, X1 + pad, Y1 + pad
    img = Image.new('RGBA', (W, H), (0, 0, 0, 0)); d = ImageDraw.Draw(img)
    d.rounded_rectangle((X0, Y0, X1, Y1), radius=18, outline=GOLD + (255,), width=6)
    f = F('Bold', 40); tw = d.textlength(label, font=f); pw, ph = tw + 56, 76
    px = min(max(40, (X0 + X1) / 2 - pw / 2), W - 40 - pw)
    py = Y0 - ph - 18 if (Y0 - ph - 18 > PY + 10 and not below) else Y1 + 18
    d.rounded_rectangle((px, py, px + pw, py + ph), radius=38, fill=GOLD + (255,)); d.text((px + 28, py + 14), label, font=f, fill=(10, 10, 10, 255))
    cx = min(max(px + 50, (X0 + X1) / 2), px + pw - 50)
    if py < Y0: d.polygon([(cx - 16, py + ph - 2), (cx + 16, py + ph - 2), (cx, py + ph + 22)], fill=GOLD + (255,))
    else: d.polygon([(cx - 16, py + 2), (cx + 16, py + 2), (cx, py - 22)], fill=GOLD + (255,))
    img.save(path)

def pdf_clip(pdf, path, secs=3.6):
    """Page 1 of a PDF the app generated, shown on a phone-sized dark canvas (static, 3.6 s)."""
    png = path + '_p'; subprocess.run(['pdftoppm', '-r', '170', '-f', '1', '-l', '1', '-png', pdf, png], check=True)
    pg = Image.open(png + '-1.png').convert('RGB'); w = 744; pg = pg.resize((w, int(pg.height * w / pg.width)), Image.LANCZOS)
    c = Image.new('RGB', (SW, SH), (24, 24, 24)); y = 70; c.paste(pg, ((SW - w) // 2, y))
    ImageDraw.Draw(c).rectangle(((SW - w) // 2 - 1, y - 1, (SW - w) // 2 + w, y + pg.height), outline=(60, 60, 60))
    c.save(path + '.png')
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-loop', '1', '-t', str(secs), '-i', path + '.png', '-vf', 'fps=30,format=yuv420p', '-c:v', 'libx264', '-crf', '16', path], check=True)
    return (SW - w) // 2, y, (SW - w) // 2 + w, y + pg.height

def build(lang):
    run = RUNS[lang]; ev = {}; rc = {}
    for e in json.load(open(f'{run}/events.json')):
        ev[e['name']] = e['t']
        if e.get('rect'): rc[e['name'][:-6]] = e['rect']
    css = lambda name, clamp=None, ext=0: ((lambda r: (r['x0'] * 2, max(r['y0'], clamp or -1e9) * 2, r['x1'] * 2, (r['y1'] + ext) * 2))(rc[name]))
    rec = f'{run}/rec.mp4'; tmp = os.path.join(OUT, '_tmp'); os.makedirs(tmp, exist_ok=True)
    cs_box = pdf_clip(f'{run}/costsheet.pdf', f'{tmp}/{lang}-cost.mp4'); pp_box = pdf_clip(f'{run}/proposal.pdf', f'{tmp}/{lang}-prop.mp4')
    t = L[lang]; E = lambda n: ev[n]
    # each clip: segments [(src, a, b, speed)] and callouts [(seg_idx, a, b, box, label)]
    clips = [
      dict(segs=[('rec', E('start') + 0.2, E('sqft_end') + 0.2, 1.3)],
           calls=[(0, E('scope_start'), E('scope_end'), css('scope'), t['scope']), (0, E('city_start'), E('city_end'), css('city'), t['city']),
                  (0, E('trade_start'), E('trade_end'), css('trade'), t['trade'])]),
      dict(segs=[('rec', E('step2_start') - 0.2, E('labor_end') + 0.2, 1.0)],
           calls=[(0, E('margins_start'), E('margins_end'), css('margins', 60, 70 if rc['margins']['y0'] < 60 else 0), t['margins']), (0, E('labor_start'), E('labor_end'), css('labor'), t['labor'])]),
      dict(segs=[('rec', E('analyze_click') - 0.3, E('questions_ready'), max(1.0, (E('questions_ready') - E('analyze_click')) / 1.4)),
                 ('rec', E('questions_ready'), E('answers_done'), 1.7)],
           calls=[(1, E('q0_start'), E('q0_end'), css('q0'), t['q0']), (1, E('q2_start'), E('q2_end'), css('q2'), t['q2'])]),
      dict(segs=[('rec', E('calc_click') - 0.3, E('result_ready') + 0.3, max(1.0, (E('result_ready') - E('calc_click')) / 3.5)),
                 ('rec', E('result_ready') + 0.3, E('final_end'), 1.0)],
           calls=[(1, E('price_start'), E('price_end') + 0.2, css('price'), t['price']), (1, E('range_start'), E('range_end'), css('range'), t['rng'], 'below'),
                  (1, E('final_start'), E('final_end'), css('final'), t['final'])]),
      dict(segs=[('rec', E('pdfgrid_start') - 1.2, E('pdfgrid_end'), 1.0), ('cost', 0, 3.6, 1.0), ('prop', 0, 3.6, 1.0)],
           calls=[(0, E('pdfgrid_start'), E('pdfgrid_end'), css('pdfgrid'), t['grid']), (1, 0.2, 3.5, cs_box, t['cost']), (2, 0.2, 3.5, pp_box, t['prop'])]),
    ]
    thumbs = []
    for ci, c in enumerate(clips):
        cid = IDS[ci]; base = f'{tmp}/{cid}-{lang}-frame.png'; frame_png(t['steps'][ci], t['titles'][ci], base)
        srcs = {'rec': rec, 'cost': f'{tmp}/{lang}-cost.mp4', 'prop': f'{tmp}/{lang}-prop.mp4'}
        durs = [(b - a) / sp for (_, a, b, sp) in c['segs']]; offs = [sum(durs[:i]) for i in range(len(durs))]; total = sum(durs)
        inputs = ['-loop', '1', '-t', f'{total:.2f}', '-i', base]; fc = []; idx = {}
        for k, (s, a, b, sp) in enumerate(c['segs']):
            if s not in idx: inputs += ['-i', srcs[s]]; idx[s] = len(inputs) // 2 - 0  # placeholder fixed below
        # recompute input indices properly
        inputs = ['-loop', '1', '-t', f'{total:.2f}', '-i', base]; idx = {}; n = 1
        for s in dict.fromkeys(s for s, *_ in c['segs']): inputs += ['-i', srcs[s]]; idx[s] = n; n += 1
        labels = []
        for k, (s, a, b, sp) in enumerate(c['segs']):
            fc.append(f'[{idx[s]}:v]trim=start={a:.3f}:end={b:.3f},setpts=(PTS-STARTPTS)/{sp:.4f},fps=30,scale={PW}:{PH},setsar=1,format=yuv420p[s{k}]'); labels.append(f'[s{k}]')
        fc.append(''.join(labels) + f'concat=n={len(labels)}:v=1:a=0[ph]'); fc.append(f'[0:v][ph]overlay={PX}:{PY}[b0]'); last = 'b0'; cstarts = []
        for j, (si, a, b, box, label, *opt) in enumerate(c['calls']):
            o0 = offs[si] + (a - c['segs'][si][1]) / c['segs'][si][3]; o1 = offs[si] + (b - c['segs'][si][1]) / c['segs'][si][3]
            o0 = max(o0, 0.1); o1 = min(o1, total - 0.05); cp = f'{tmp}/{cid}-{lang}-c{j}.png'; callout_png(box, label, cp, below=bool(opt)); cstarts.append((o0, o1))
            inputs += ['-loop', '1', '-t', f'{total:.2f}', '-i', cp]; ni = n; n += 1
            fc.append(f'[{ni}:v]format=rgba,fade=t=in:st={o0:.2f}:d=0.25:alpha=1,fade=t=out:st={max(o0 + 0.3, o1 - 0.25):.2f}:d=0.25:alpha=1[c{j}]')
            fc.append(f'[{last}][c{j}]overlay=0:0[b{j + 1}]'); last = f'b{j + 1}'
        out = os.path.join(OUT, f'even-{cid}-{lang}.mp4')
        subprocess.run(['ffmpeg', '-v', 'error', '-y'] + inputs + ['-filter_complex', ';'.join(fc), '-map', f'[{last}]', '-t', f'{total:.2f}', '-c:v', 'libx264', '-preset', 'veryfast', '-crf', '20',
                        '-pix_fmt', 'yuv420p', '-r', '30', '-movflags', '+faststart', out], check=True)
        tt = (cstarts[1][0] + cstarts[1][1]) / 2 if len(cstarts) > 1 else total / 2
        th = os.path.join(OUT, f'thumb-{cid}-{lang}.png'); subprocess.run(['ffmpeg', '-v', 'error', '-y', '-ss', f'{tt:.2f}', '-i', out, '-frames:v', '1', th], check=True)
        print(out, round(total, 1)); thumbs.append(th)
    return thumbs

th = {l: build(l) for l in ('en', 'es')}
sheet = Image.new('RGB', (5 * 360, 2 * 640 + 0), (0, 0, 0))
for r, l in enumerate(('en', 'es')):
    for i, p in enumerate(th[l]): sheet.paste(Image.open(p).convert('RGB').resize((360, 640)), (i * 360, r * 640))
sheet.save(os.path.join(OUT, 'thumbnails.png'))
